import mongoose from "mongoose";

const emergencyCaseSchema = new mongoose.Schema(
    {
        // ==========================================
        // STEP 1: THE QUICK REPORT (Minimal & Fast)
        // ==========================================
        reporter: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "User",
            required: true,
        },
        assignedNgo: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Ngo",
            default: null,
        },
        animalInfo: {
            species: { type: String, required: true }, // e.g., Dog, Cat, Cow
            quickDescription: { type: String, required: true }, // "Hit by car on highway"
        },
        location: {
            type: { type: String, enum: ["Point"], default: "Point" },
            coordinates: { type: [Number], required: true }, // [longitude, latitude]
            address: { type: String },
        },
        media: [{ type: String }], // Photos (Optional but encouraged)

        // ==========================================
        // STEP 2: OPTIONAL AI CARE (Filled out later)
        // ==========================================
        aiCare: {
            isRequested: { type: Boolean, default: false },
            isConscious: { type: Boolean },
            isBleeding: { type: Boolean },
            canMove: { type: Boolean },
            behavior: { type: String }, // e.g., "Aggressive", "Scared"
            aiGuidanceProvided: { type: String }, // The response generated by the AI
        },

        // ==========================================
        // STEP 3: VOLUNTEER HOOK
        // ==========================================
        // If an NGO accepts this case but needs physical help, they flip this to true.
        // The actual VolunteerRequest model will link back to this EmergencyCase ID!
        requiresVolunteers: {
            type: Boolean,
            default: false,
        },

        // ==========================================
        // RESCUE TRACKING PIPELINE
        // ==========================================
        status: {
            type: String,
            enum: [
                "Reported", 
                "Help Requested", 
                "Rescue Accepted", 
                "Rescuer On The Way", 
                "Animal Picked Up", 
                "At Veterinary Facility", 
                "Resolved"
            ],
            default: "Reported",
        },
    },
    { timestamps: true }
);

// 2dsphere index for instantaneous location-based NGO matching
emergencyCaseSchema.index({ location: "2dsphere" });

export const EmergencyCase = mongoose.model("EmergencyCase", emergencyCaseSchema);